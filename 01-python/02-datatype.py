# Numbers - Integers, Boolean, Real Floating, Complex numbers

# Strings
descript = "This is description"
print(f"First word: {descript[0]}") #First character
print(f"First word: {descript[0: 3]}")  # 0 to 2 (3 is not included)
print(f"First word: {descript[:8]}") # starting from 0 to 7th index
print(f"First word: {descript[5:]}") # starting from 4th index till end
print(f"First word: {descript[::-1]}") ## shorthand of reverse